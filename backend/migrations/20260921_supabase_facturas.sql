-- MIGRACIÓN OFICIAL: TABLAS FACTURAS Y DETALLE_FACTURAS (SUPABASE POSTGRESQL)
-- Basado estrictamente en el diseño de arquitectura y esquema gráfico oficial:
-- Tabla Facturas:
--   # idFacturas          int8 (PK, Identity)
--   ◆ Fecha               timestamptz DEFAULT now()
--   ◆ Estado              varchar DEFAULT 'Pagado'
--   ◆ Total               numeric DEFAULT 0.00
--   ◆ Usuarios_idUsuarios int8 (FK Usuarios)
-- ==============================================================================

-- 1. Asegurar columnas de cliente en tabla Usuarios si faltan
ALTER TABLE IF EXISTS "Usuarios" ADD COLUMN IF NOT EXISTS "Cedula" VARCHAR(50);
ALTER TABLE IF EXISTS "Usuarios" ADD COLUMN IF NOT EXISTS "Telefono" VARCHAR(50);

-- En caso de nombres en minúsculas en Postgres
ALTER TABLE IF EXISTS usuarios ADD COLUMN IF NOT EXISTS cedula VARCHAR(50);
ALTER TABLE IF EXISTS usuarios ADD COLUMN IF NOT EXISTS telefono VARCHAR(50);

-- 2. Crear tabla Facturas (Entidad Principal en Backend)
CREATE TABLE IF NOT EXISTS "Facturas" (
  "idFacturas" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Fecha" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "Estado" VARCHAR(50) NOT NULL DEFAULT 'Pagado',
  "Total" NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  "Usuarios_idUsuarios" BIGINT NOT NULL
);

-- Crear índices de búsqueda rápida
CREATE INDEX IF NOT EXISTS "idx_facturas_usuario" ON "Facturas" ("Usuarios_idUsuarios");
CREATE INDEX IF NOT EXISTS "idx_facturas_fecha" ON "Facturas" ("Fecha" DESC);

-- 3. Crear tabla Detalle_Facturas (Renglones de compra)
CREATE TABLE IF NOT EXISTS "Detalle_Facturas" (
  "idDetalles" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Factura_idFactura" BIGINT NOT NULL REFERENCES "Facturas" ("idFacturas") ON DELETE CASCADE,
  "Productos_idProductos" BIGINT NOT NULL,
  "Cantidad" INTEGER NOT NULL DEFAULT 1,
  "Precio_Unitario" NUMERIC(10, 2) NOT NULL DEFAULT 0.00
);

CREATE INDEX IF NOT EXISTS "idx_detalle_factura" ON "Detalle_Facturas" ("Factura_idFactura");

-- 4. Comentarios institucionales
COMMENT ON TABLE "Facturas" IS 'Tabla oficial de almacenamiento contable de compras y cotizaciones (Recibos de Compra)';
COMMENT ON TABLE "Detalle_Facturas" IS 'Desglose de productos comprados vinculados al Recibo de Compra';
